/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */
  resetByWatchdog = __HAL_RCC_GET_FLAG(RCC_FLAG_IWDGRST) ? TRUE : FALSE;
  __HAL_RCC_CLEAR_RESET_FLAGS();
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */
  /* Stop the watchdog counting while halted in the debugger. */
  __HAL_DBGMCU_FREEZE_IWDG();
  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_CAN1_Init();
  MX_CAN2_Init();
  MX_SPI1_Init();
  MX_SPI2_Init();
  MX_TIM2_Init();
  MX_USART1_UART_Init();
  MX_ADC1_Init();
  MX_IWDG_Init();
  /* USER CODE BEGIN 2 */
  INIT_STEP(STAGE_UART, sys_uartInit());
  INIT_STEP(STAGE_CAN, sys_canInit());
  INIT_STEP(STAGE_FLASH, sys_flashInit());
  INIT_STEP(STAGE_CC_DAC, sys_ccDacInit());
  INIT_STEP(STAGE_INFO_DAC, sys_infoDacInit());
  INIT_STEP(STAGE_IMU, sys_imuInit());
  if (resetByWatchdog) {
    CLI_Print("Reset: watchdog\r\n");
  }
  INIT_STEP(STAGE_CLI, CLI_Init());
  vehicle_data_init(&vehicle_data);
  sys_wallClockInit(&wall_clock);
  cc_state_init();            // Initialize cc state
  cc_control_init();
  INIT_STEP(STAGE_CC_INPUTS, cc_inputs_init(&cc_input_config));
  initStage = STAGE_RUNNING;

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    cc_control_service();

    /* TODO: Ingest CAN into vehicle_data here. Until then speed stays invalid. */
    const uint32_t now_ms = sys_getTimeMs();
    float measured_speed_mps = vehicle_data.current_speed.value;
    uint8_t speed_valid = validate_cc_data(&vehicle_data, now_ms);

    /* The CLI test stub, when on, replaces the real speed (dry run). */
    float test_speed_mps;
    if (cc_control_speed(&test_speed_mps)) {
        measured_speed_mps = test_speed_mps;
        speed_valid = TRUE;
    }

    cc_inputs_t inputs = cc_inputs_update();
    cc_state_update(inputs.mode_pressed,
                    inputs.cruise_allowed && speed_valid);
    cc_control_update(cc_state_get(), measured_speed_mps, speed_valid);

    CLI_Process();

    /* Once per pass, only after everything above has run. */
    HAL_IWDG_Refresh(&hiwdg);
  }
  /* USER CODE END 3 */
}

